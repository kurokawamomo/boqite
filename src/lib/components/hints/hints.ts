const FALLBACK_HINTS = ['今日も一歩ずつ、簿記の基礎を積み上げていこう！'];

/** "b3-u03" のような unitId から章番号を取り出す（見つからなければ null） */
export function extractChapterNumber(unitId: string): number | null {
	const match = unitId.match(/u0*(\d+)/);
	if (!match) return null;
	return Number(match[1]);
}

/** unitId に対応する章のヒントを1本ランダムに返す（該当なしはフォールバック文言） */
export function pickHint(unitId: string): string {
	const chapter = extractChapterNumber(unitId);
	const pool = (chapter !== null ? HINTS_BY_CHAPTER[chapter] : undefined) ?? FALLBACK_HINTS;
	return pool[Math.floor(Math.random() * pool.length)];
}
